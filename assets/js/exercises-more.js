/* KALOS — עוד 5 תרגילים: שכיבת סמיכה על קיר ועל ברכיים, תלייה פעילה, הרמות ברכיים בתלייה ועליה למדרגה.
   נטען אחרי exercises-extra.js, ומעדכן את מפת התרגילים ואזורי הגוף. */
(function () {
  'use strict';
  const KX = window.KX;
  const { L, add, pivotTorso } = KX.fig;
  const deg = (r) => (r * 180) / Math.PI;
  const LEG = L.thigh + L.shin;
  const ARM = L.upper + L.fore;
  const BODY = LEG + L.torso;
  const F = 300;
  const floor = { k: 'floor', y: F };
  const P = (o) => Object.assign({ hip: add(o.S, L.torso, o.t + 180) }, o);
  const X = (p, o) => Object.assign({}, p, o);
  const sag = (p) => X(pivotTorso(p, 9), { bend: -12, ht: -22, mark: 'hip' });

  const MORE = [
    /* ---------- שכיבת סמיכה על קיר ---------- */
    (() => {
      const foot = [120, F], H = [330, 176];
      /* מוצא זווית גוף כך שהכתף נמצאת במרחק d מהידיים (גוף ישר מהרצפה עד הכתף) */
      const at = (d) => {
        let best = null;
        for (let a = 12; a <= 86; a += 0.1) {
          const S = add(foot, BODY, a);
          if (S[0] >= H[0] || S[1] < H[1] - 24) continue;
          const e = Math.abs(Math.hypot(S[0] - H[0], S[1] - H[1]) - d);
          if (!best || e < best.e) best = { a, e };
        }
        return { hip: add(foot, LEG, best.a), t: best.a, hand: H, foot, es: 1, ks: -1 };
      };
      const top = at(ARM - 0.5), bot = at(34);
      return {
        id: 'wallpush', name: 'שכיבת סמיכה על קיר', en: 'Wall Push-up', cat: 'push', level: 1, rx: '3×10–20',
        muscles: ['חזה', 'כתף קדמית', 'יד אחורית'], equip: 'קיר',
        summary: 'נקודת ההתחלה הכי עדינה לדחיפה: עומדים מול קיר ודוחפים אותו. מתאים למתחילים לגמרי, לחזרה אחרי פציעה, ולחימום.',
        steps: ['עמוד במרחק צעד מהקיר, ידיים על הקיר בגובה הכתפיים וברוחב כתפיים.', 'הגוף ישר מהעקבים ועד הראש, בטן וישבן פעילים.', 'כופף מרפקים והטה את החזה אל הקיר, מרפקים בזווית של כ־45°.', 'דחוף את הקיר ושוב הגע לידיים ישרות.'],
        cues: ['ככל שהרגליים רחוקות יותר מהקיר — התרגיל קשה יותר', 'הראש בהמשך הגוף, בלי להקדים את החזה', 'עבור לשיפוע כשאתה מבצע 3×20 נקיות'],
        mistakes: ['אגן שבור לאחור', 'מרפקים פתוחים לצדדים ב־90°', 'טווח קצר מדי'],
        easier: 'צעד קרוב יותר לקיר', harder: 'שכיבת סמיכה בשיפוע',
        anim: { gear: [floor, { k: 'box', x: 330, y: 20, w: 90, h: F - 20 }], hl: ['arm', 'torso'], frames: () => [
          { p: top, d: 1000, h: 500, c: 'ידיים על הקיר, גוף ישר כקרש' },
          { p: bot, d: 1400, h: 250, c: 'החזה מתקרב לקיר, מרפקים ב־45°' },
        ], bad: () => [
          { p: X(top, { bend: 0 }), d: 800, h: 250, c: 'התחלה…' },
          { p: X(bot, { hip: add(bot.hip, 22, 180), bend: 14, mark: 'hip' }), d: 1200, h: 800, c: '✗ האגן נשבר לאחור — הגוף לא בקו ישר' },
        ] },
      };
    })(),

    /* ---------- שכיבת סמיכה על ברכיים ---------- */
    (() => {
      const knee = [150, F - 5], SH = L.thigh + L.torso;
      const foot = add(knee, L.shin - 0.5, 150);
      const mk = (a, hx) => {
        const hip = add(knee, L.thigh, a), S = add(knee, SH, a);
        return { hip, t: a, hand: [hx != null ? hx : S[0], F], foot, es: 1, ks: -1 };
      };
      const top = mk(Math.asin((ARM - 0.5) / SH) * 180 / Math.PI);
      const bot = mk(Math.asin(34 / SH) * 180 / Math.PI, top.hand[0]);
      return {
        id: 'kneepush', name: 'שכיבת סמיכה על ברכיים', en: 'Knee Push-up', cat: 'push', level: 1, rx: '3×8–15',
        muscles: ['חזה', 'כתף קדמית', 'יד אחורית'], equip: 'ללא ציוד',
        summary: 'שכיבת סמיכה קלה יותר: הברכיים על הרצפה מקצרות את המנוף. חשוב לשמור על קו ישר מהברכיים ועד הראש ולא לשבור את האגן.',
        steps: ['ברכיים על הרצפה (מומלץ על מחצלת), ידיים מתחת לכתפיים או מעט רחב יותר.', 'הרם את הרגליים מהרצפה והצלב קרסוליים.', 'כווץ בטן וישבן, כך שהגוף ישר מהברכיים ועד הראש.', 'רד עד שהחזה כמעט נוגע ברצפה ודחוף חזרה.'],
        cues: ['קו ישר: ברכיים–אגן–כתפיים–ראש', 'מרפקים ב־45° ולא פתוחים לצדדים', 'עבור לשכיבת סמיכה מלאה כשמגיעים ל־3×15'],
        mistakes: ['ישבן באוויר או אגן שוקע', 'ראש נופל קדימה', 'טווח חלקי'],
        easier: 'שכיבת סמיכה על קיר או בשיפוע', harder: 'שכיבת סמיכה מלאה',
        anim: { gear: [floor], hl: ['arm', 'torso'], frames: () => [
          { p: top, d: 950, h: 600, c: 'ברכיים על הרצפה, גוף ישר מהברכיים עד הראש' },
          { p: bot, d: 1500, h: 250, c: 'החזה יורד לרצפה, מרפקים ב־45°' },
        ], bad: () => [
          { p: sag(top), d: 950, h: 600, c: '✗ האגן שוקע — הגוף לא בקו ישר' },
          { p: sag(bot), d: 1400, h: 250, c: '✗ הגב התחתון קורס והראש נופל' },
        ] },
      };
    })(),

    /* ---------- תלייה פעילה ---------- */
    (() => {
      const H = [240, 30];
      const passive = P({ S: [238, 114], t: 91, hand: H, foot: [244, 298], es: 1, ks: -1 });
      const active = P({ S: [239, 112], t: 91, ht: -4, hand: H, foot: [244, 296], es: 1, ks: -1 });
      return {
        id: 'deadhang', name: 'תלייה פעילה', en: 'Active Hang', cat: 'pull', level: 1, rx: '3×20–40 שנ׳',
        muscles: ['אמות', 'לאטס', 'שכמות', 'כתפיים'], equip: 'מוט מתח',
        summary: 'הבסיס לכל מתח: תלייה עם כתפיים "מורדות" ושכמות פעילות. מחזק אחיזה, מגן על הכתפיים ולומד לשלוט בשכמות לפני שמתחילים למשוך.',
        steps: ['אחוז במוט באחיזה עליונה ברוחב כתפיים או מעט יותר.', 'תלה עם ידיים ישרות, רגליים צמודות ובטן פעילה.', 'הורד את השכמות הרחק מהאוזניים, כך שהגוף מתרומם בכמה סנטימטרים.', 'החזק את התנוחה בלי לכופף מרפקים.'],
        cues: ['"הרחק כתפיים מהאוזניים" ולא כפיפת מרפקים', 'הבהונות מצביעות מטה, בלי נדנוד', 'אפשר להתחיל מתלייה עם רגליים על הרצפה'],
        mistakes: ['כתפיים שמוטות עד האוזניים', 'מרפקים כפופים', 'נדנוד'],
        easier: 'תלייה עם רגליים על כיסא', harder: 'משיכות שכמות ← מתח שליליים',
        anim: { gear: [{ k: 'bar', x: 240, y: 30 }], hl: ['arm', 'torso'], frames: () => [
          { p: passive, d: 1500, h: 700, c: 'תלייה רפויה, כתפיים בגובה האוזניים' },
          { p: active, d: 900, h: 1700, c: 'שכמות מורדות, ידיים ישרות, גוף מתרומם מעט' },
        ], bad: () => [
          { p: P({ S: [238, 92], t: 91, hand: H, foot: [244, 292], es: 1, ks: -1, mark: 'E' }), d: 900, h: 900, c: '✗ מרפקים כפופים — זה כבר מתח ולא תלייה' },
          { p: P({ S: [230, 112], t: 80, hand: H, foot: [296, 276], es: 1, ks: -1, mark: 'hip' }), d: 700, h: 900, c: '✗ נדנוד — מאבדים שליטה בשכמות' },
        ] },
      };
    })(),

    /* ---------- הרמות ברכיים בתלייה ---------- */
    (() => {
      const H = [240, 30], S = [238, 114];
      const hang = P({ S, t: 91, hand: H, foot: [244, 298], es: 1, ks: -1 });
      const topHip = add(S, L.torso, 100 + 180);
      const top = P({ S, t: 100, hand: H, foot: [topHip[0] + 54, topHip[1] + 58], es: 1, ks: -1 });
      return {
        id: 'hangknee', name: 'הרמות ברכיים בתלייה', en: 'Hanging Knee Raise', cat: 'core', level: 1, rx: '3×8–15',
        muscles: ['בטן ישרה', 'מכופפי ירך', 'אמות'], equip: 'מוט מתח',
        summary: 'הגרסה הקלה של הרמות רגליים בתלייה. מלמדת להטות את האגן ולהרים את הברכיים בשליטה, בלי נדנוד.',
        steps: ['תלה במוט עם שכמות פעילות ורגליים צמודות.', 'הטה את האגן לאחור וכווץ בטן.', 'הרם ברכיים עד לגובה הבטן או מעלה.', 'הורד לאט, 2–3 שניות, בלי לתת לגוף להתנדנד.'],
        cues: ['האגן מתגלגל כלפי מעלה — לא רק הרמת רגליים', 'הורדה איטית', 'עצור לרגע למעלה'],
        mistakes: ['נדנוד ותנופה', 'ירידה חופשית', 'כתפיים שמוטות'],
        easier: 'תלייה פעילה, או הרמות ברכיים בשכיבה', harder: 'הרמות רגליים ישרות בתלייה',
        anim: { gear: [{ k: 'bar', x: 240, y: 30 }], hl: ['torso', 'leg'], frames: () => [
          { p: hang, d: 1500, h: 400, c: 'תלייה יציבה, רגליים צמודות' },
          { p: top, d: 1200, h: 500, c: 'האגן מתגלגל והברכיים עולות עד הבטן' },
        ], bad: () => [
          { p: P({ S: [246, 114], t: 76, hand: H, foot: [196, 290], es: 1, ks: -1, mark: 'hip' }), d: 800, h: 100, c: '✗ תנופה לאחור…' },
          { p: P({ S: [231, 112], t: 112, hand: H, foot: [322, 226], es: 1, ks: -1, mark: 'hip' }), d: 700, h: 200, c: '✗ …והמומנטום מרים את הרגליים, לא הבטן' },
        ] },
      };
    })(),

    /* ---------- עלייה למדרגה ---------- */
    (() => {
      const BX = 258, BY = 250;
      const S1 = [236, 118];
      const start = { hip: [236, 190], t: 85, hand: add(S1, 52, -30), foot: [BX + 20, BY], foot2: [196, F], es: 1, ks: -1, ks2: -1 };
      const hipTop = [BX + 50, BY - LEG + 3];
      const Stop = add(hipTop, L.torso, 90);
      const top = { hip: hipTop, t: 90, hand: add(Stop, 52, -30), foot: [BX + 50, BY], foot2: [BX + 82, BY - 54], es: 1, ks: -1, ks2: -1 };
      return {
        id: 'stepup', name: 'עלייה למדרגה', en: 'Step-up', cat: 'legs', level: 1, rx: '3×8–12 לכל רגל',
        muscles: ['ארבע ראשי', 'ישבן', 'המסטרינג'], equip: 'מדרגה / ספסל / כיסא יציב',
        summary: 'תרגיל רגל אחת פשוט ויעיל. עלייה על משטח בונה כוח ויציבות, ומכינה לסקוואט בולגרי ולפיסטול.',
        steps: ['הנח רגל שלמה על המשטח, כך שהברך מעל הקרסול.', 'דחוף דרך העקב של הרגל העליונה ועלה לעמידה מלאה.', 'הרם את הברך השנייה ועצור לרגע למעלה.', 'רד לאט בשליטה והחלף רגל אחרי כל הסט.'],
        cues: ['העבודה מהרגל העליונה — אל תדחוף מהרגל שעל הרצפה', 'גו זקוף וחזה פתוח', 'משטח גבוה יותר = קשה יותר'],
        mistakes: ['דחיפה מהרגל התחתונה', 'ברך קורסת פנימה', 'נפילה בירידה'],
        easier: 'משטח נמוך יותר', harder: 'בולגרי ספליט סקוואט ← פיסטול',
        anim: { gear: [floor, { k: 'box', x: BX, y: BY, w: 110, h: F - BY }], hl: ['leg'], frames: () => [
          { p: start, d: 1200, h: 400, c: 'רגל אחת על המדרגה, ברך מעל הקרסול' },
          { p: top, d: 1100, h: 800, c: 'דחיפה דרך העקב, עמידה מלאה והרמת ברך' },
        ], bad: () => [
          { p: start, d: 1000, h: 300, c: 'התחלה…' },
          { p: X(top, { hip: [BX + 50, BY - LEG + 3], t: 98, ht: -8, foot2: [BX - 4, F - 6], mark: 'K' }), d: 1000, h: 1200, c: '✗ הרגל התחתונה דוחפת מהרצפה — הרגל העליונה לא עובדת' },
        ] },
      };
    })(),
  ];

  MORE.forEach((e) => KX.exercises.push(e));

  /* אזורי גוף */
  const G = {
    wallpush: 'chest arms shoulders', kneepush: 'chest arms shoulders', deadhang: 'back arms',
    hangknee: 'abs', stepup: 'legs glutes',
  };
  MORE.forEach((e) => (e.groups = G[e.id].split(' ')));
  MORE.forEach((e) => (KX.exMap[e.id] = e));

  /* קישור מסלולי ההתקדמות לתרגילים החדשים */
  const link = (track, name, id) => { const t = KX.progressions.find((p) => p.id === track); const s = t && t.steps.find((x) => x.n === name); if (s) s.ex = id; };
  link('push', 'שכיבת סמיכה על קיר', 'wallpush');
  link('pull', 'תלייה פעילה + משיכות שכמות', 'deadhang');
  link('fl', 'תלייה פעילה', 'deadhang');
})();
